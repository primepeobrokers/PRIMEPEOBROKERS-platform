"use server";

import { createAdminClient } from "@/lib/supabase/admin";
import { claimRequest, clientIp } from "@/lib/auth/throttle";
import { currentTenantIdForWrite, leadAttribution, getTenant } from "@/lib/tenant/resolve";
import { brandFor } from "@/lib/tenant/email-brand";
import {
  TOTAL_STEPS,
  sanitizeAnswers,
  visibleAnswers,
  validateStep,
  formatAnswer,
  answeredCategory,
  type Answers,
} from "@/lib/discovery/schema";
import {
  sendResumeLink,
  sendSubmissionConfirmation,
  sendSubmissionNotification,
} from "@/lib/email";

/*
 * All writes from the (unauthenticated) discovery flow run here, server-side,
 * with the service-role client. The client never talks to the database.
 * A draft can only be modified by presenting its (id, resume_token) pair:
 * the token is generated by the database and only ever handed to the browser
 * that created the draft (and to the visitor's email).
 */

const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export interface DraftHandle {
  draftId: string;
  token: string;
}

interface DraftRow {
  id: string;
  resume_token: string;
  status: string;
  answers: Answers;
  steps_completed: number;
}

/**
 * Mirrors the handful of answers the console lists and filters on into flat
 * columns. The full record stays in the answers jsonb; these are for querying.
 */
function denormalize(answers: Answers) {
  const num = (id: string) => {
    const v = answers[id];
    const n = Number(v);
    return typeof v === "string" && v !== "" && Number.isFinite(n) ? n : null;
  };
  const str = (id: string) => {
    const v = answers[id];
    return typeof v === "string" && v !== "" ? v : null;
  };
  return {
    company_name: str("company"),
    contact_name: str("fullName"),
    contact_email: str("email"),
    fte_count: num("fte"),
    benefits_spend: num("spend"),
    current_setup: answers["provider"]
      ? formatAnswer("provider", answers)
      : null,
    category: answeredCategory(answers) ?? null,
  };
}

async function loadGuardedDraft(
  handle: DraftHandle,
): Promise<{ row: DraftRow } | { error: string }> {
  if (!UUID_RE.test(handle.draftId) || !UUID_RE.test(handle.token)) {
    return { error: "That draft could not be found." };
  }
  const supabase = createAdminClient();
  /*
    The tenant predicate is Phase 3's addition. The (id, resume_token) pair
    was sufficient while one tenant existed: the token is a DB-generated uuid,
    so it is not enumerable. It is still not enumerable, but this client is
    service-role and therefore bypasses RLS, so without the tenant filter a
    resume link from one partner's subdomain would resolve and update that
    partner's draft when opened on a different partner's host.
  */
  const { data, error } = await supabase
    .from("submissions")
    .select("id, resume_token, status, answers, steps_completed")
    .eq("id", handle.draftId)
    .eq("resume_token", handle.token)
    .eq("tenant_id", await currentTenantIdForWrite())
    .maybeSingle();
  if (error || !data) return { error: "That draft could not be found." };
  return { row: data as DraftRow };
}

/**
 * Persists progress. Creates the draft on the first save; afterwards updates
 * it, guarded by the resume token. `stepsCompleted` is the count of steps the
 * visitor has finished (0–6).
 */
export async function saveDraft(input: {
  handle: DraftHandle | null;
  answers: unknown;
  stepsCompleted: number;
  /** 'shop' (default) or 'renewal', set by the home page entry point. */
  intent?: string;
}): Promise<
  | { ok: true; handle: DraftHandle }
  | { ok: false; error: string }
> {
  const answers = sanitizeAnswers(input.answers);
  const stepsCompleted = Math.max(
    0,
    Math.min(TOTAL_STEPS, Math.trunc(Number(input.stepsCompleted) || 0)),
  );
  const supabase = createAdminClient();

  if (!input.handle) {
    // Creating a brand-new draft is the only unauthenticated write that adds a
    // row, so it is the one that needs a ceiling.
    const gate = await claimRequest("save_draft", await clientIp(), 20, "1 hour");
    if (!gate.allowed) {
      return {
        ok: false,
        error: "Too many drafts started from this connection. Try again shortly.",
      };
    }

    const { data, error } = await supabase
      .from("submissions")
      .insert({
        // The partner whose subdomain captured this lead. Phase 1 and 2 used
        // a constant; the resolver falls back to the house tenant on an
        // unrecognised host, so a lead is never dropped.
        tenant_id: await currentTenantIdForWrite(),
        answers,
        steps_completed: stepsCompleted,
        intent: input.intent === "renewal" ? "renewal" : "shop",
        // Stamped once, on the insert. A draft that is later resumed keeps
        // the partner that captured it even if the visitor comes back on a
        // different host from the emailed link.
        ...(await leadAttribution()),
        ...denormalize(answers),
      })
      .select("id, resume_token")
      .single();
    if (error || !data) {
      console.error("[discovery] draft insert failed", error);
      return { ok: false, error: "Saving failed. Your answers are still in this tab. Try again." };
    }
    return {
      ok: true,
      handle: { draftId: data.id, token: data.resume_token },
    };
  }

  const guarded = await loadGuardedDraft(input.handle);
  if ("error" in guarded) return { ok: false, error: guarded.error };
  if (guarded.row.status === "complete") {
    return { ok: false, error: "This record was already submitted." };
  }

  const { error } = await supabase
    .from("submissions")
    .update({
      answers,
      steps_completed: Math.max(stepsCompleted, guarded.row.steps_completed),
      ...denormalize(answers),
    })
    .eq("id", input.handle.draftId)
    .eq("resume_token", input.handle.token)
    .eq("tenant_id", await currentTenantIdForWrite());
  if (error) {
    console.error("[discovery] draft update failed", error);
    return { ok: false, error: "Saving failed. Your answers are still in this tab. Try again." };
  }
  return { ok: true, handle: input.handle };
}

/**
 * Final submission. Re-validates every step server-side; the client's
 * validation is a convenience, not the guard.
 */
export async function submitRecord(input: {
  handle: DraftHandle | null;
  answers: unknown;
}): Promise<
  | { ok: true; ref: number }
  | { ok: false; error: string; fieldErrors?: Record<string, string> }
> {
  const answers = visibleAnswers(sanitizeAnswers(input.answers));

  for (let i = 0; i < TOTAL_STEPS; i++) {
    const errors = validateStep(i, answers);
    if (Object.keys(errors).length > 0) {
      return {
        ok: false,
        error: `Step ${i + 1} has answers that need attention.`,
        fieldErrors: errors,
      };
    }
  }

  // Ensure a draft row exists, then mark it complete.
  const saved = await saveDraft({
    handle: input.handle,
    answers,
    stepsCompleted: TOTAL_STEPS,
  });
  if (!saved.ok) return saved;

  const supabase = createAdminClient();
  const { data, error } = await supabase
    .from("submissions")
    .update({
      status: "complete",
      submitted_at: new Date().toISOString(),
    })
    .eq("id", saved.handle.draftId)
    .eq("resume_token", saved.handle.token)
    .eq("tenant_id", await currentTenantIdForWrite())
    .select("id, ref")
    .single();
  if (error || !data) {
    console.error("[discovery] submit failed", error);
    return { ok: false, error: "Submitting failed. Nothing was lost. Try again." };
  }

  await supabase.from("submission_events").insert({
    // Must match the submission's own tenant: 0006's composite
    // (tenant_id, submission_id) FK rejects any other value.
    tenant_id: await currentTenantIdForWrite(),
    submission_id: data.id,
    actor: "client",
    action: "submitted",
    detail: "Submitted through discovery flow",
  });

  // Notifications are best-effort: a mail failure must never lose the lead.
  // Branded for the host the lead submitted on: a partner's lead hears from
  // the partner, and the partner and the house team are both told.
  const contactEmail = answers["email"];
  const contactName = answers["fullName"];
  try {
    const brand = brandFor(await getTenant());
    /*
      Both sends at once. They are independent, each is a ~300ms call to
      Resend, and awaiting them in series put that whole time on the submit
      button's spinner for work the visitor never sees. allSettled, not all,
      so one failing address cannot stop the other message.
    */
    const sends: Promise<unknown>[] = [
      sendSubmissionNotification({ ref: data.ref, id: data.id, answers, brand }),
    ];
    if (typeof contactEmail === "string" && contactEmail) {
      sends.push(
        sendSubmissionConfirmation({
          to: contactEmail,
          ref: data.ref,
          name: typeof contactName === "string" ? contactName : "",
          brand,
        }),
      );
    }
    for (const r of await Promise.allSettled(sends)) {
      if (r.status === "rejected") {
        console.error("[discovery] notification email failed", r.reason);
      }
    }
  } catch (e) {
    console.error("[discovery] notification email failed", e);
  }

  return { ok: true, ref: data.ref };
}

/** Emails the visitor a link back to their draft. */
export async function requestResumeLink(input: {
  handle: DraftHandle | null;
  answers: unknown;
  stepsCompleted: number;
  email: string;
}): Promise<{ ok: true } | { ok: false; error: string }> {
  const email = String(input.email ?? "").trim();
  if (!/^[^@\s]+@[^@\s.]+\.[^@\s]+$/.test(email)) {
    return { ok: false, error: "That address is missing an @ or a domain." };
  }

  /*
    This action mails an arbitrary caller-supplied address from the brand's
    verified domain, with no sign-in required. Unmetered, that is a relay: it
    burns the Resend quota and, worse, spends the domain's sending reputation
    on traffic we did not intend.

    Two ceilings. Per-connection stops one caller fanning out across many
    addresses; per-recipient stops the same inbox being mailed repeatedly from
    rotating connections.
  */
  const ip = await clientIp();
  const byIp = await claimRequest("resume_link_ip", ip, 5, "1 hour");
  const byRecipient = await claimRequest(
    "resume_link_to",
    email.toLowerCase(),
    3,
    "1 hour",
  );
  if (!byIp.allowed || !byRecipient.allowed) {
    return {
      ok: false,
      error: "That link was just sent. Check your inbox, including spam.",
    };
  }

  // Make sure the latest answers are on the draft before mailing the link.
  const saved = await saveDraft({
    handle: input.handle,
    answers: input.answers,
    stepsCompleted: input.stepsCompleted,
  });
  if (!saved.ok) return saved;

  const supabase = createAdminClient();
  await supabase
    .from("submissions")
    .update({ resume_email: email })
    .eq("id", saved.handle.draftId)
    .eq("resume_token", saved.handle.token)
    .eq("tenant_id", await currentTenantIdForWrite());

  try {
    const sent = await sendResumeLink({
      to: email,
      token: saved.handle.token,
      stepsCompleted: input.stepsCompleted,
      // The link is built on this host's origin, so a partner's draft
      // reopens on the partner's subdomain where its tenant matches.
      brand: brandFor(await getTenant()),
    });
    if (!sent.ok) {
      return {
        ok: false,
        error: "The link could not be sent. Your answers are saved in this browser; try again in a moment.",
      };
    }
  } catch (e) {
    console.error("[discovery] resume link email failed", e);
    return { ok: false, error: "Sending failed. Try again in a moment." };
  }
  return { ok: true };
}

/**
 * "Talk to a broker first": the short form at /talk.
 *
 * Stored as a complete submission rather than a draft, so it lands in the
 * console as a lead like any other. A partial row would read as an abandoned
 * form, which this is not. The answers use the discovery field ids so the
 * console detail view, the export, and the notification email need no special
 * case: contactPreference says "call" and notes carries what they wrote.
 */
export async function requestCall(input: {
  fullName: string;
  email: string;
  phone?: string;
  company?: string;
  notes?: string;
  bestTime?: string;
}): Promise<
  | { ok: true; ref: number }
  | { ok: false; error: string; fieldErrors?: Record<string, string> }
> {
  const clean = (v: unknown, max: number) =>
    typeof v === "string" ? v.trim().slice(0, max) : "";
  const fullName = clean(input.fullName, 200);
  const email = clean(input.email, 320);

  const fieldErrors: Record<string, string> = {};
  if (!fullName) fieldErrors.fullName = "A name, so the broker knows who to ask for.";
  if (!/^[^@\s]+@[^@\s.]+\.[^@\s]+$/.test(email)) {
    fieldErrors.email = "That address is missing an @ or a domain.";
  }
  if (Object.keys(fieldErrors).length > 0) {
    return { ok: false, error: "Check the highlighted fields.", fieldErrors };
  }

  // Same ceiling logic as a new draft: this is an unauthenticated insert.
  const gate = await claimRequest("request_call", await clientIp(), 10, "1 hour");
  if (!gate.allowed) {
    return {
      ok: false,
      error: "Too many requests from this connection. Try again shortly.",
    };
  }

  const answers: Answers = { fullName, email, contactPreference: "call" };
  const phone = clean(input.phone, 60);
  const company = clean(input.company, 200);
  const notes = clean(input.notes, 2000);
  const bestTime = clean(input.bestTime, 200);
  if (phone) answers.phone = phone;
  if (company) answers.company = company;
  if (notes) answers.notes = notes;
  if (bestTime) answers.bestTime = bestTime;

  const supabase = createAdminClient();
  const tenantId = await currentTenantIdForWrite();
  const { data, error } = await supabase
    .from("submissions")
    .insert({
      tenant_id: tenantId,
      answers,
      steps_completed: 0,
      intent: "shop",
      status: "complete",
      submitted_at: new Date().toISOString(),
      ...denormalize(answers),
    })
    .select("id, ref")
    .single();
  if (error || !data) {
    console.error("[talk] insert failed", error);
    return {
      ok: false,
      error: "Sending failed. Nothing was lost. Try again in a moment.",
    };
  }

  await supabase.from("submission_events").insert({
    tenant_id: tenantId,
    submission_id: data.id,
    actor: "client",
    action: "submitted",
    detail: "Asked for a call from the homepage",
  });

  // Best-effort, like the discovery submit: mail must never lose the lead.
  // The team hears about it, and the person gets a confirmation, so the form
  // is never silent even when the team inbox is unset.
  try {
    const brand = brandFor(await getTenant());
    // Both at once, for the same reason as submitRecord above.
    const results = await Promise.allSettled([
      sendSubmissionNotification({
        ref: data.ref,
        id: data.id,
        answers,
        brand,
        kind: "call",
      }),
      sendSubmissionConfirmation({
        to: email,
        ref: data.ref,
        name: fullName,
        brand,
        kind: "call",
      }),
    ]);
    for (const r of results) {
      if (r.status === "rejected") {
        console.error("[talk] notification email failed", r.reason);
      }
    }
  } catch (e) {
    console.error("[talk] notification email failed", e);
  }

  return { ok: true, ref: data.ref };
}
